// TypeScript types of the API's responses, generated from the FastAPI OpenAPI schema
// (src/lib/openapi.json, written by scripts/export_openapi.py). `--check` fails when the committed
// src/lib/api-types.ts is stale. web/test/api-contract.test.ts holds the site's own types
// (src/lib/types.ts) to these.
import openapiTS, { astToString } from "openapi-typescript";
import { readFileSync, writeFileSync } from "node:fs";

const schema = new URL("../src/lib/openapi.json", import.meta.url);
const out = new URL("../src/lib/api-types.ts", import.meta.url);
const header = "// Generated by scripts/api-types.mjs from openapi.json (the FastAPI schema). Do not edit.\n";
const text = header + astToString(await openapiTS(schema, { defaultNonNullable: false }));
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    console.error("src/lib/api-types.ts is stale: run `npm run api-types`");
    process.exit(1);
  }
  console.log("api-types.ts matches openapi.json");
} else {
  writeFileSync(out, text);
  console.log("wrote src/lib/api-types.ts");
}
